"""Writes src/hans_table.rs from OpenCC's Traditional-to-Simplified
dictionaries (TSCharacters.txt, TSPhrases.txt; Apache-2.0, Copyright
BYVoid and the OpenCC contributors, https://github.com/BYVoid/OpenCC).

    python3 scripts/hans_table.py path/to/opencc/dictionary > src/hans_table.rs

Only characters in the CJK Unified Ideographs block (U+4E00-U+9FFF) on
both sides are kept: what whisper writes, and what the caption fonts
draw. Where OpenCC lists several Simplified forms the first, its own
preferred one, is taken. Every phrase keeps its length in characters,
which the converter relies on to keep a caption's timed pieces aligned
with its text; the script refuses one that does not.
"""
import sys

def basic(c):
    return 0x4E00 <= ord(c) <= 0x9FFF

def main(folder):
    chars = {}
    for line in open(f"{folder}/TSCharacters.txt", encoding="utf-8"):
        key, values = line.rstrip("\n").split("\t")
        first = values.split(" ")[0]
        if len(key) == 1 and basic(key) and basic(first) and key != first:
            chars[key] = first
    phrases = {}
    for line in open(f"{folder}/TSPhrases.txt", encoding="utf-8"):
        key, values = line.rstrip("\n").split("\t")
        first = values.split(" ")[0]
        if len(key) != len(first):
            sys.exit(f"phrase {key} -> {first} changes length")
        if not all(basic(c) for c in key + first):
            continue
        # Only where the phrase says something the characters alone do not.
        if "".join(chars.get(c, c) for c in key) != first:
            phrases[key] = first
    out = sys.stdout
    out.write("// SPDX-License-Identifier: AGPL-3.0-or-later AND Apache-2.0\n")
    out.write("// Generated by scripts/hans_table.py from OpenCC's TSCharacters.txt and\n")
    out.write("// TSPhrases.txt (Apache-2.0, Copyright BYVoid and the OpenCC contributors,\n")
    out.write("// https://github.com/BYVoid/OpenCC). Do not edit by hand.\n\n")
    out.write("/// Traditional character to its Simplified form, sorted by the first.\n")
    out.write(f"pub(crate) static CHARS: [(char, char); {len(chars)}] = [\n")
    for key in sorted(chars):
        out.write(f"    ('{key}', '{chars[key]}'),\n")
    out.write("];\n\n")
    out.write("/// Phrases whose Simplified form is not their characters' one by one,\n")
    out.write("/// sorted; each keeps its length in characters.\n")
    out.write(f"pub(crate) static PHRASES: [(&str, &str); {len(phrases)}] = [\n")
    for key in sorted(phrases):
        out.write(f'    ("{key}", "{phrases[key]}"),\n')
    out.write("];\n")

main(sys.argv[1])
